/**
 * Pure Markdown rendering of the calibration results (no Convex, no I/O), so the
 * same renderer backs both the vitest report generator and the tsx runner.
 */

import type { RunMetrics } from "./harness";
import {
  GRADES,
  DOMAINS,
  ENTRIES,
  NOISE_PROFILES,
  NOISE_SEEDS,
  implicatedKnobs,
  type CellSummary,
} from "./grid";

function fmt(n: number, d = 1): string {
  if (!Number.isFinite(n)) return "–";
  return Number.isInteger(n) && d === 0 ? String(n) : n.toFixed(d);
}

function percentile(sorted: number[], p: number): number {
  if (sorted.length === 0) return 0;
  const idx = (sorted.length - 1) * p;
  const lo = Math.floor(idx);
  const hi = Math.ceil(idx);
  if (lo === hi) return sorted[lo];
  return sorted[lo] + (sorted[hi] - sorted[lo]) * (idx - lo);
}

function statLine(label: string, xs: number[], d = 1): string {
  const s = [...xs].sort((a, b) => a - b);
  return `| ${label} | ${fmt(percentile(s, 0), d)} | ${fmt(percentile(s, 0.5), d)} | ${fmt(
    percentile(s, 0.9),
    d,
  )} | ${fmt(percentile(s, 1), d)} | ${fmt(s.reduce((a, b) => a + b, 0) / (s.length || 1), d)} |`;
}

/** Render a domain×entry (rows) × grade (columns) matrix of one metric, over the
 *  CLEAN summaries only (the noise-free calibration surface). */
function matrix(
  summaries: CellSummary[],
  pick: (s: CellSummary) => number,
  d = 1,
): string {
  const byKey = new Map<string, CellSummary>();
  for (const s of summaries) if (s.noise === "clean") byKey.set(`${s.domain}|${s.entry}|${s.grade}`, s);
  const header = `| domain / entry | ${GRADES.map((g) => `G${g}`).join(" | ")} |`;
  const sep = `| --- | ${GRADES.map(() => "---:").join(" | ")} |`;
  const rows: string[] = [];
  for (const domain of DOMAINS) {
    for (const entry of ENTRIES) {
      const cells = GRADES.map((g) => {
        const s = byKey.get(`${domain}|${entry}|${g}`);
        return s ? fmt(pick(s), d) : "–";
      });
      rows.push(`| ${shortDomain(domain)} · ${shortEntry(entry)} | ${cells.join(" | ")} |`);
    }
  }
  return [header, sep, ...rows].join("\n");
}

function shortDomain(d: string): string {
  return d.replace(/-/g, " ").replace("arithmetic", "arith.").replace("measurement", "meas.");
}
function shortEntry(e: string): string {
  return e === "you-pick" ? "You-Pick" : "default";
}

/** One worst-cell block: headline stats + implicated knobs. */
function renderCell(prefix: string, s: CellSummary): string {
  const lines: string[] = [];
  lines.push(
    `### ${prefix} \`${s.domain}\` · ${shortEntry(s.entry)} · G${s.grade} · ${s.noise}  — badness ${fmt(
      s.badness,
    )}`,
  );
  lines.push("");
  lines.push(
    `- probes **${fmt(s.probes)}**, IDK burden **${fmt(s.idkBurden)}**, overshoot(max) **${fmt(
      s.overshootMaxGrades,
    )} grades**, oscillation **${fmt(s.oscillationGlobal)}**`,
  );
  lines.push(
    `- over-credit **${fmt(s.overCredit)}** (${fmt(s.overCreditFrac * 100, 0)}%), under-credit **${fmt(
      s.underCredit,
    )}** (${fmt(s.underCreditFrac * 100, 0)}%), grade-error **${fmt(s.gradeErrorMean)}**; cap-hit ${fmt(
      s.capHitRate * 100,
      0,
    )}%`,
  );
  const knobs = implicatedKnobs(s);
  if (knobs.length === 0) {
    lines.push("- **implicated knob:** none over threshold (bad by accumulation, not one dominant knob)");
  } else {
    lines.push("- **implicated knob(s):**");
    for (const k of knobs) lines.push(`  - \`${k.knob}\` — ${k.reason}`);
  }
  lines.push("");
  return lines.join("\n");
}

export function renderReport(runs: RunMetrics[], summaries: CellSummary[]): string {
  const clean = summaries.filter((s) => s.noise === "clean");
  const out: string[] = [];

  out.push("# Placement Calibration Report");
  out.push("");
  out.push(
    "> **POST-FIX — the You-Pick grade prior is now applied.** This lane began as measurement-only (J9, Option A: no constant tuned); acting on its finding was the separate, approved change now shipped in `submitPlacementAnswer`. A cold You-Pick entry (no `gradeLevel`) now seeds its first-probe anchor at the domain's foundational floor grade (`domainFloorGrade`) instead of blindly ~1/3 up each strand; the affect-safe ring ceiling stays tied to the real grade (undefined ⇒ uncapped), mirroring the mixed-path start/ceiling split so a conservative prior can never strand a strong picker. This report is generated by the harness under `evals/placement-calibration/`, which drives the REAL production placement path (`api.practiceSkills.submitPlacementAnswer` via `convex-test`) with synthetic ORACLE scholars. It is regenerated, not hand-written — see the README to reproduce.",
  );
  out.push("");
  out.push(
    `Grid: **${DOMAINS.length} domains** × **${ENTRIES.length} entry kinds** × **${GRADES.length} true-frontier grades** × **${NOISE_PROFILES.length} noise profiles** (clean = 1 seed; each noisy profile = ${NOISE_SEEDS} seeds). Total runs measured: **${runs.length}**, aggregated into **${summaries.length} cells**.`,
  );
  out.push("");

  // ── Method ──
  out.push("## What an oracle is, and what each metric means");
  out.push("");
  out.push(
    "A **synthetic oracle** knows every graph node at/below a true frontier grade **G** in a domain, and nothing above it. On a probe it answers the item's true answer when it knows the node, or an honest **\"I haven't learned this yet\"** (IDK) when it doesn't. Noise variants add `p(slip)` (a careless wrong answer on a KNOWN node) and `p(guess-correct)` (a lucky right answer on an UNKNOWN multiple-choice node). The real server grades every answer and decides the next probe — the harness never reimplements the search.",
  );
  out.push("");
  out.push(
    "**Entry kinds.** *default* = the system knows the scholar's grade and passes it as a prior (`gradeLevel = G`); the affect-safe first probe is grade-anchored. *You-Pick* = the scholar picked the domain cold, with **no** chronological grade prior (the pilot's geometry case). It now opens at the domain's foundational floor grade (`domainFloorGrade`) — the grade prior — rather than blindly ~1/3 up each strand, so a cold pick opens at/below the kid and trusts upward instead of overshooting.",
  );
  out.push("");
  out.push("| metric | meaning |");
  out.push("| --- | --- |");
  out.push("| **probes** | probes to converge (probe-log length) |");
  out.push("| **IDK burden** | honest IDKs the kid eats (server `unknown` outcomes) |");
  out.push("| **overshoot (max)** | how many grades ABOVE the true frontier the first probe of a strand opens (worst strand) |");
  out.push("| **oscillation** | direction changes in served difficulty across the run |");
  out.push("| **over-credit** | nodes credited that the oracle does NOT know |");
  out.push("| **under-credit** | known nodes NOT credited |");
  out.push(
    "| **grade-error** | rank(told grade) − rank(the IDEAL grade for this oracle): + over-places, − under-places. Measured vs. the ideal label (`derivePlacedThroughGrade` of the oracle's true known set), so a domain with no content at/below G — where a null label is correct — scores 0, not a spurious deficit |",
  );
  out.push("");

  // ── Headline distributions ──
  out.push("## Headline distributions (clean oracles)");
  out.push("");
  out.push("Across all clean cells (the noise-free calibration surface):");
  out.push("");
  out.push("| metric | min | median | p90 | max | mean |");
  out.push("| --- | ---: | ---: | ---: | ---: | ---: |");
  out.push(statLine("probes", clean.map((s) => s.probes)));
  out.push(statLine("IDK burden", clean.map((s) => s.idkBurden)));
  out.push(statLine("overshoot max (grades)", clean.map((s) => s.overshootMaxGrades)));
  out.push(statLine("oscillation (global)", clean.map((s) => s.oscillationGlobal)));
  out.push(statLine("over-credit (nodes)", clean.map((s) => s.overCredit)));
  out.push(statLine("under-credit (nodes)", clean.map((s) => s.underCredit)));
  out.push(statLine("|grade-error|", clean.map((s) => s.gradeErrorAbsMean)));
  out.push("");

  // ── Per-metric matrices ──
  out.push("## Distributions by domain × entry × grade (clean)");
  out.push("");
  out.push("### Probes to converge");
  out.push("");
  out.push(matrix(clean, (s) => s.probes));
  out.push("");
  out.push("### IDK burden (honest IDKs eaten)");
  out.push("");
  out.push(matrix(clean, (s) => s.idkBurden));
  out.push("");
  out.push("### Overshoot — max grades above the true frontier at first probe");
  out.push("");
  out.push(matrix(clean, (s) => s.overshootMaxGrades));
  out.push("");
  out.push("### Oscillation — global direction changes in served difficulty");
  out.push("");
  out.push(matrix(clean, (s) => s.oscillationGlobal));
  out.push("");
  out.push("### Over-credit (nodes credited but not known)");
  out.push("");
  out.push(matrix(clean, (s) => s.overCredit));
  out.push("");
  out.push("### Under-credit (known nodes not credited)");
  out.push("");
  out.push(matrix(clean, (s) => s.underCredit));
  out.push("");
  out.push("### Grade-error (told-grade − true grade)");
  out.push("");
  out.push(matrix(clean, (s) => s.gradeErrorMean));
  out.push("");

  // ── You-Pick vs default (the start-prior contrast) ──
  out.push("## You-Pick vs default entry — the grade-prior contrast");
  out.push("");
  out.push(
    "The same oracle, entered cold (You-Pick) vs. with an accurate grade prior (default). Means over clean cells, per domain:",
  );
  out.push("");
  out.push("| domain | probes You-Pick | probes default | IDK You-Pick | IDK default | overshoot You-Pick | overshoot default |");
  out.push("| --- | ---: | ---: | ---: | ---: | ---: | ---: |");
  for (const domain of DOMAINS) {
    const yp = clean.filter((s) => s.domain === domain && s.entry === "you-pick");
    const df = clean.filter((s) => s.domain === domain && s.entry === "default-foundational");
    const m = (xs: number[]) => xs.reduce((a, b) => a + b, 0) / (xs.length || 1);
    out.push(
      `| ${shortDomain(domain)} | ${fmt(m(yp.map((s) => s.probes)))} | ${fmt(
        m(df.map((s) => s.probes)),
      )} | ${fmt(m(yp.map((s) => s.idkBurden)))} | ${fmt(m(df.map((s) => s.idkBurden)))} | ${fmt(
        m(yp.map((s) => s.overshootMaxGrades)),
      )} | ${fmt(m(df.map((s) => s.overshootMaxGrades)))} |`,
    );
  }
  out.push("");

  // ── Noise effect ──
  out.push("## Noise effect on frontier accuracy");
  out.push("");
  out.push(
    "How the two noise axes move the credited-vs-true frontier error (means over all cells of each profile):",
  );
  out.push("");
  out.push("| noise profile | over-credit | under-credit | |grade-error| | IDK burden |");
  out.push("| --- | ---: | ---: | ---: | ---: |");
  for (const { name } of NOISE_PROFILES) {
    const g = summaries.filter((s) => s.noise === name);
    const m = (xs: number[]) => xs.reduce((a, b) => a + b, 0) / (xs.length || 1);
    out.push(
      `| ${name} | ${fmt(m(g.map((s) => s.overCredit)), 2)} | ${fmt(
        m(g.map((s) => s.underCredit)),
        2,
      )} | ${fmt(m(g.map((s) => s.gradeErrorAbsMean)), 2)} | ${fmt(m(g.map((s) => s.idkBurden)))} |`,
    );
  }
  out.push("");
  out.push(
    "**Reading it:** `slip15` (careless misses on KNOWN nodes) drives systematic UNDER-crediting — a single miss at the top of what the kid knows caps the binary search's ceiling with no higher pass to override it, stranding a whole prefix below the true frontier. `guess25` (lucky MC guesses on UNKNOWN nodes) drives OVER-crediting — a guessed-correct probe raises the confirmed-pass floor. Both are convergence-rule signatures (the search has no slip tolerance and treats one lucky guess as proof).",
  );
  out.push("");
  out.push(
    "**Domain-floor cells.** Several domains have NO content at/below low grades (e.g. ratio-proportion-percent and integers-coordinates begin at grade 6). A You-Pick oracle below that floor knows nothing in the domain, so it eats an all-IDK run (see the IDK matrix) and correctly places at the floor (grade-error 0). Those cells are not a search bug — they implicate **entry gating / start-prior**: the kid should not be able to cold-pick a domain wholly above them without a prior that opens at the floor or a prerequisite gate.",
  );
  out.push("");

  // ── Worst cells ──
  // Distinct base cells (domain|entry|grade) — take each base cell's worst noise
  // variant, so the top-3 are three different SCENARIOS, not noise twins.
  const byBadness = [...summaries].sort((a, b) => b.badness - a.badness);
  const worst: CellSummary[] = [];
  const seenBase = new Set<string>();
  for (const s of byBadness) {
    const base = `${s.domain}|${s.entry}|${s.grade}`;
    if (seenBase.has(base)) continue;
    seenBase.add(base);
    worst.push(s);
    if (worst.length === 3) break;
  }
  out.push("## The 3 worst cells and the knob each implicates");
  out.push("");
  out.push(
    "Ranked by a composite **badness** = IDK·1 + overshoot·1.5 + oscillation·0.5 + over-credit-frac·10 + under-credit-frac·10 + |grade-error|·1 + capHit·5 (documented, not tuned; credit error is normalized to a fraction of the relevant node pool so a large domain doesn't mechanically dominate). For each, the knob attribution is **diagnosis only** — no constant is changed in this lane.",
  );
  out.push("");
  for (let i = 0; i < worst.length; i++) out.push(renderCell(`${i + 1}.`, worst[i]));

  // Auxiliary lenses so both failure families surface, not just the composite.
  const affect = (s: CellSummary) => s.idkBurden + s.overshootMaxGrades * 1.5 + s.oscillationGlobal * 0.5;
  const accuracy = (s: CellSummary) => s.overCreditFrac * 10 + s.underCreditFrac * 10 + s.gradeErrorAbsMean;
  const worstAffect = [...summaries].sort((a, b) => affect(b) - affect(a))[0];
  const worstAccuracy = [...summaries].sort((a, b) => accuracy(b) - accuracy(a))[0];
  out.push("### Worst by AFFECT (IDK + overshoot + oscillation)");
  out.push("");
  out.push(renderCell("→", worstAffect));
  out.push("### Worst by ACCURACY (over/under-credit + grade-error)");
  out.push("");
  out.push(renderCell("→", worstAccuracy));

  // ── Per-knob synthesis ──
  out.push("## Synthesis — which knob owns which failure");
  out.push("");
  const withKnob = (knob: string) =>
    summaries.filter((s) => implicatedKnobs(s).some((k) => k.knob === knob));
  const sp = withKnob("start-prior");
  const ss = withKnob("step-size");
  const cr = withKnob("convergence-rule");
  out.push(
    `- **start-prior** (\`affectSafeFirstProbeIndex\` / \`firstProbeTargets\` / grade ring) — implicated in **${sp.length}** cells. Signature: the search OPENS grades above the kid and the kid eats IDKs before the search finds their level. Concentrated in **You-Pick** entries and in domains whose strand FLOORS sit above the oracle's grade (e.g. geometry's angle/coordinate/volume strands have no grade-2 content). The default-vs-You-Pick table above quantifies the win an accurate prior already buys — where the gap is large, the missing prior is the lever.`,
  );
  out.push("");
  out.push(
    `- **step-size** (binary-search midpoint stride + cross-strand round-robin) — implicated in **${ss.length}** cells. Signature: served difficulty changes direction many times (the pilot's \"moves up and down for 15 questions\"). Worst in multi-strand domains where the round-robin interleaves strands at different depths within one felt sequence.`,
  );
  out.push("");
  out.push(
    `- **convergence-rule** (per-strand \`MAX_PROBES_PER_STRAND\` / global \`PLACEMENT_GLOBAL_CAP\`, the trust-upward monotonicity assumption, the lo≥hiNoRing stop, and the \`derivePlacedThroughGrade\` label) — implicated in **${cr.length}** cells. Signature: frontier error (over/under-credit) where the topological order is not grade-monotone, a lucky-MC-guess raising the floor, or a single-grade LABEL that understates node-level credit.`,
  );
  out.push("");
  out.push("---");
  out.push("");
  out.push(
    "_Regenerate: `PLACEMENT_CALIBRATION_FULL=1 npx vitest run evals/placement-calibration/report.test.ts` (see README)._",
  );
  out.push("");
  return out.join("\n");
}
